// tools/site/templates/inventory-rules.mjs — prometheus/rules/ibmmq.inventory.yml
//
// One recorded series per queue manager of the environment (`ibmmq:inventory:qmgr`, vector(1)
// with the inventory's labels): what the site says should be reporting. Vantage single adds
// IBMMQQueueManagerSilent, the join of that inventory against up{job="ibmmq-exporter"} (the
// exporter job carries the static qmgr label there, design §8): an inventoried queue manager
// with no exporter series for two minutes. In a dual-vantage site the native endpoint answers
// that question (IBMMQQueueManagerDown), so no alert is rendered.

import { ruleLabels, targetLabels, flow } from './lib.mjs';

export function render(ctx) {
  const t = ctx.timing, single = ctx.vantage === 'single';
  const records = ctx.qmgrs.map(qm => {
    const { source: _s, ...labels } = targetLabels(ctx, qm, 'inventory');
    return `      - record: ibmmq:inventory:qmgr
        expr: vector(1)
        labels: ${flow({ ...labels, vantage: ctx.vantage })}
`;
  }).join('');
  const silent = single ? `
      # Inventoried but not reporting: no up{job="ibmmq-exporter"} series joins this queue manager.
      # The exporter for it is not running or not scraped, or the queue manager was removed
      # without updating the inventory (regenerate the site).
      - alert: IBMMQQueueManagerSilent
        expr: ibmmq:inventory:qmgr unless on (qmgr) up{job="ibmmq-exporter"}
        for: 2m
        labels: ${ruleLabels(ctx, 'SEV2', 'qmgr_reachability')}
        annotations:
          summary: "Queue manager {{ $labels.qmgr }} is in the ${ctx.env} inventory but nothing reports it"
          description: "No exporter series for {{ $labels.qmgr }} ({{ $labels.site }}, {{ $labels.shape }}) for 2 minutes: its client exporter is down or unscraped, or the inventory is stale."
          runbook: runbooks/qmgr-silent.md
` : '';
  return `# Inventory of environment ${ctx.env}, GENERATED by gen-site from the site inventory: one series per
# queue manager the site says exists. Dashboards and the certification harness read it to list
# the fleet; a single-vantage site alerts when an inventoried queue manager has no telemetry.
groups:
  - name: ibmmq.inventory
    interval: ${t.dur(t.interval)}
    rules:
${records}${silent}`;
}
