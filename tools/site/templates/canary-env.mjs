// tools/site/templates/canary-env.mjs — qmgrs/<QM>/canary.env
//
// The &canary_env block of docker-compose.yaml as KEY=VALUE (compose env_file, a systemd
// EnvironmentFile or a ConfigMap): the canary's queue manager, CONNAME, SVRCONN channel, user,
// password file, queues, probe interval, OTLP endpoint and resource attributes (design §7.1:
// deployment.environment is the environment). TLS queue managers get MQ_CCDT_URL,
// MQ_KEY_REPOSITORY and MQ_CIPHER, read by the canary from increment 3. Secrets are file
// references (design R5). tools/test-site.mjs T10 compares the lab file with the compose block
// key by key.

import { connName } from './lib.mjs';

export function render(ctx, qm) {
  const t = ctx.timing, p = ctx.p;
  const tls = qm.params.tls || null;
  const lines = [
    `# canary.env — the synthetic put/get canary of ${qm.name} (${ctx.env}), GENERATED by gen-site.`,
    '# The &canary_env block of docker-compose.yaml as KEY=VALUE; MODE=producer|consumer reuse it.',
    'MODE=canary',
    `MQ_QMGR=${qm.name}`,
    `MQ_CONNAME=${connName(qm)}`,
    `MQ_CHANNEL=${qm.params.channels.canary}`,
    `MQ_USER=${p.users.canary}`,
    `MQ_PASSWORD_FILE=${qm.params.credentials.canary_secret}`,
    `CANARY_QUEUE=${p.canary_queue}`,
    ...(p.orders_queue ? [`ORDERS_QUEUE=${p.orders_queue}`] : []),
    `INTERVAL_MS=${t.probe * 1000}`,
    'OTEL_SERVICE_NAME=mq-canary',
    `OTEL_EXPORTER_OTLP_ENDPOINT=${ctx.endpoints.otlp}`,
    `OTEL_RESOURCE_ATTRIBUTES=service.namespace=ibmmq,deployment.environment=${ctx.env},service.version=0.1.0`,
  ];
  if (tls) {
    lines.push(`MQ_CCDT_URL=${tls.ccdt_url}`, `MQ_KEY_REPOSITORY=${tls.key_repository}`);
    if (tls.cipher) lines.push(`MQ_CIPHER=${tls.cipher}`);
  }
  return lines.join('\n') + '\n';
}
