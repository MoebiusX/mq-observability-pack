// tools/site/templates/alertmanager.mjs — alertmanager/alertmanager.yml and alertmanager.fleet.yml
//
// The lab file (stack/alertmanager/alertmanager.yml) with the damping from the timing model and
// the receivers from the environment's `receivers` / `secrets` (design §7.3). The root receiver is
// SEV3's; a SEV1 route always exists (its own group_wait), SEV2 gets a route when its receiver
// differs from the root. Every route matches `environment = "<env>"`: Prometheus attaches that
// external label to its alerts (prometheus.mjs), so one Alertmanager can serve several
// environments (alertmanager.fleet.yml, --env all). Secrets are file references (design R5).
// The lab renders today's file plus the environment matcher on its SEV1 route (asserted, T10).

import { receiversOf, receiverBlock, receiverName } from './lib.mjs';

function routes(ctx, indent, prefix) {
  const a = ctx.timing.alertmanager;
  const rs = receiversOf(ctx);
  const root = rs.find(r => r.sev === 'SEV3');
  const lines = [];
  for (const r of rs) {
    if (r.sev === 'SEV3') continue;
    if (r.sev === 'SEV2' && r.name === root.name) continue;
    lines.push(`${indent}- matchers: [ environment = "${ctx.env}", severity = ${r.sev} ]`);
    lines.push(`${indent}  receiver: ${prefix}${r.name}`);
    if (r.sev === 'SEV1') lines.push(`${indent}  group_wait: ${a.group_wait_sev1}`);
  }
  return { root, lines };
}

function receiverBlocks(ctx, prefix) {
  const seen = new Set();
  return receiversOf(ctx).filter(r => !seen.has(r.name) && seen.add(r.name)).map(r => receiverBlock(ctx, r.ref, `${prefix}${r.name}`)).join('\n');
}

export function render(ctx) {
  const a = ctx.timing.alertmanager;
  const { root, lines } = routes(ctx, '    ', '');
  return `# Alertmanager — routes every pack alert ${ctx.lab ? 'to the harness alert-sink (webhook ledger)' : `of environment ${ctx.env} by severity`}.
# ${ctx.lab ? 'Production routing (MS Teams / PagerDuty) is declared in packs/ibmmq.pack.yaml spec.alerting' : 'GENERATED by gen-site from the site inventory (environments.' + ctx.env + '.receivers); secrets are file references'}.
global:
  resolve_timeout: ${a.resolve_timeout}

route:
  receiver: ${root.name}
  group_by: [alertname, qmgr, queue]
  group_wait: ${a.group_wait}${ctx.lab ? '          # lab: minimal damping so MTTD reflects the pipeline' : ''}
  group_interval: ${a.group_interval}
  repeat_interval: ${a.repeat_interval}
  routes:
${lines.join('\n')}

receivers:
${receiverBlocks(ctx, '')}
`;
}

/** alertmanager.fleet.yml: every environment's routes under its environment matcher, receivers prefixed by environment. */
export function renderFleet(ctxs) {
  const secs = ctxs[0].timing.secs;
  const resolve = ctxs.map(c => c.timing.alertmanager.resolve_timeout).reduce((x, y) => (secs(y) > secs(x) ? y : x));
  const envRoutes = ctxs.map(ctx => {
    const a = ctx.timing.alertmanager;
    const { root, lines } = routes(ctx, '        ', `${ctx.env}-`);
    return `    - matchers: [ environment = "${ctx.env}" ]
      receiver: ${ctx.env}-${root.name}
      group_wait: ${a.group_wait}
      group_interval: ${a.group_interval}
      repeat_interval: ${a.repeat_interval}
${lines.length ? `      routes:\n${lines.join('\n')}\n` : ''}`;
  }).join('');
  return `# Alertmanager for the whole fleet (${ctxs.map(c => c.env).join(', ')}), GENERATED by gen-site --env all:
# one subtree per environment under its environment matcher; receivers are prefixed by
# environment so names never collide. Alerts without an environment label reach fleet-default,
# a receiver with no configuration (they are dropped, visibly, in the Alertmanager UI).
global:
  resolve_timeout: ${resolve}

route:
  receiver: fleet-default
  group_by: [alertname, qmgr, queue]
  routes:
${envRoutes}
receivers:
  - name: fleet-default
${ctxs.map(ctx => receiverBlocks(ctx, `${ctx.env}-`)).join('\n')}
`;
}

