#!/usr/bin/env node
// Generates stack/prometheus/rules/<pack>.burn.yml from the pack's spec.policy with Observogram's
// burn-rate compiler (vendor/observogram/lib/burn-rules.mjs, copied from Observogram, never edited
// here): one multi-window burn-rate alert per declared window, one forecast alert per entry, and
// the error-budget recording rules the dashboards read. The five PromQL deviations from
// Observogram's compile.mjs, each measured on the live lab, are documented in that library's
// header and in docs/catalogue-evidence/ibmmq.md §8.
//
//   node tools/gen-burn-rules.mjs                 # packs/ibmmq.pack.yaml → stack/prometheus/rules/ibmmq.burn.yml
//   node tools/gen-burn-rules.mjs --pack-snippet  # the recording rules for spec.queries.recording_rules
//   node tools/gen-burn-rules.mjs --env prod      # production for: (2 m / 5 m / 10 m by short window)
//   node tools/gen-burn-rules.mjs --step 30       # a sample step other than the pack's own
//   PACK=packs/ibmmq-site.pack.yaml node tools/gen-burn-rules.mjs
//
// Lab timings: the sample step is the pack's declared scrape interval (10 s for the lab pack) and
// `for:` is lab-tuned (30 s / 2 m / 5 m by short window) unless --env names another environment;
// production values live in the pack's environment overrides (CLAUDE.md rule 7). Never hand-edit
// the output; `npm run burn-rules` regenerates it and CI diffs it.
//
// generateBurnRules(pack, { step, lab, runbooks, source }) is the body of the CLI as a function
// (tools/site/ibmmq.mjs and tools/test-site.mjs import it and RUNBOOK); the CLI runs only when
// this file is the entry point.
import { readFileSync, writeFileSync } from 'node:fs';
import { resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { parse as parseYaml } from '../vendor/observogram/lib/mini-yaml.mjs';
import { compileBurnRules, toYaml, packSnippet, packStepSeconds } from '../vendor/observogram/lib/burn-rules.mjs';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');

// Runbook annotations by SLI, for the alerts whose runbook exists in this repo (the ibmmq pack).
export const RUNBOOK = {
  qmgr_process_up: 'runbooks/qmgr-down.md', qmgr_reachability: 'runbooks/qmgr-unreachable.md',
  queue_depth_headroom: 'runbooks/queue-depth.md', oldest_message_age: 'runbooks/consumer-stalled.md',
  dlq_depth: 'runbooks/dlq.md', canary_success: 'runbooks/canary.md',
};
/** The runbook map a pack gets: this repo's runbooks for the ibmmq pack, none for any other. */
export const runbooksFor = (pack) => (pack?.metadata?.name === 'ibmmq' ? RUNBOOK : {});

/**
 * generateBurnRules(pack, { step, lab, runbooks, source }) → { groups, recording, forecasts,
 * warnings, burnCount, step, text, snippet }. `step` defaults to the pack's own scrape interval
 * (packStepSeconds), `lab` to true, `runbooks` to runbooksFor(pack); `source` is the pack path
 * named in the file header. `text` is the rule file, `snippet` the block for the pack's
 * spec.queries.recording_rules (--pack-snippet).
 */
export function generateBurnRules(pack, { step, lab = true, runbooks, source } = {}) {
  const r = compileBurnRules(pack, { step: step || packStepSeconds(pack), lab, runbooks: runbooks ?? runbooksFor(pack) });
  const header = [
    `# GENERATED by tools/gen-burn-rules.mjs from ${source || `packs/${pack.metadata.name}.pack.yaml`} (spec.policy) — do not edit.`,
    '# Multi-window burn-rate alerts (one per declared window), forecast alerts and the',
    '# error-budget recording rules. Names/labels follow Observogram\'s compiler; the library',
    '# header (vendor/observogram/lib/burn-rules.mjs) lists the five PromQL deviations (bad/expected',
    '# ratios, short-window floor, sustained-burn forecasts, lab for:, capped horizon + severity).',
    '# Regenerate: npm run burn-rules',
    '',
  ];
  return { ...r, text: toYaml(r.groups, header), snippet: packSnippet(r.recording) };
}

const isMain = process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url);
if (isMain) {
  const argv = process.argv.slice(2);
  const opt = (n) => { const i = argv.indexOf(n); return i >= 0 ? argv[i + 1] : null; };
  const PACK = opt('--pack') || process.env.PACK || 'packs/ibmmq.pack.yaml';
  const pack = parseYaml(readFileSync(resolve(root, PACK), 'utf8'));
  const svc = pack.metadata.name;
  const OUT = opt('--out') || `stack/prometheus/rules/${svc}.burn.yml`;
  const STEP_SEC = opt('--step') ? Number(opt('--step')) : packStepSeconds(pack);   // scrape interval = canary probe interval = subquery step
  const lab = (opt('--env') || 'lab') === 'lab';
  const r = generateBurnRules(pack, { step: STEP_SEC, lab, source: PACK });
  for (const w of r.warnings) console.error(`warning: ${w}`);
  if (argv.includes('--pack-snippet')) { console.log(r.snippet); process.exit(0); }
  writeFileSync(resolve(root, OUT), r.text);
  console.log(`${OUT}: ${r.recording.length} recording rules, ${r.burnCount} burn-rate alerts, ${r.forecasts.length} forecast alerts`);
}
