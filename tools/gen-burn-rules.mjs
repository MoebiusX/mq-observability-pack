#!/usr/bin/env node
// Generates stack/prometheus/rules/<pack>.burn.yml from the pack's spec.policy with Observogram's
// burn-rate compiler (vendor/observogram/lib/burn-rules.mjs, copied from Observogram, never edited
// here): one multi-window burn-rate alert per declared window, one forecast alert per entry, and
// the error-budget recording rules the dashboards read. The five PromQL deviations from
// Observogram's compile.mjs, each measured on the live lab, are documented in that library's
// header and in docs/catalogue-evidence/ibmmq.md §8.
//
//   node tools/gen-burn-rules.mjs                 # packs/ibmmq.pack.yaml → stack/prometheus/rules/ibmmq.burn.yml
//   node tools/gen-burn-rules.mjs --pack-snippet  # the recording rules for spec.queries.recording_rules
//   PACK=packs/ibmmq-site.pack.yaml node tools/gen-burn-rules.mjs
//
// Lab timings: the sample step is the 10 s scrape and `for:` is lab-tuned (30 s / 2 m / 5 m by
// short window); production values live in the pack's environment overrides (CLAUDE.md rule 7).
// Never hand-edit the output; `npm run burn-rules` regenerates it and CI diffs it.
import { readFileSync, writeFileSync } from 'node:fs';
import { resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { parse as parseYaml } from '../vendor/observogram/lib/mini-yaml.mjs';
import { compileBurnRules, toYaml, packSnippet } from '../vendor/observogram/lib/burn-rules.mjs';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const argv = process.argv.slice(2);
const opt = (n) => { const i = argv.indexOf(n); return i >= 0 ? argv[i + 1] : null; };
const PACK = opt('--pack') || process.env.PACK || 'packs/ibmmq.pack.yaml';
const pack = parseYaml(readFileSync(resolve(root, PACK), 'utf8'));
const svc = pack.metadata.name;
const OUT = opt('--out') || `stack/prometheus/rules/${svc}.burn.yml`;
const STEP_SEC = Number(opt('--step') || 10);     // scrape interval = canary probe interval = subquery step
// Runbook annotations by SLI, for the alerts whose runbook exists in this repo.
const RUNBOOK = svc === 'ibmmq' ? {
  qmgr_process_up: 'runbooks/qmgr-down.md', qmgr_reachability: 'runbooks/qmgr-unreachable.md',
  queue_depth_headroom: 'runbooks/queue-depth.md', oldest_message_age: 'runbooks/consumer-stalled.md',
  dlq_depth: 'runbooks/dlq.md', canary_success: 'runbooks/canary.md',
} : {};

const r = compileBurnRules(pack, { step: STEP_SEC, lab: true, runbooks: RUNBOOK });
for (const w of r.warnings) console.error(`warning: ${w}`);
if (argv.includes('--pack-snippet')) { console.log(packSnippet(r.recording)); process.exit(0); }
const header = [
  `# GENERATED by tools/gen-burn-rules.mjs from ${PACK} (spec.policy) — do not edit.`,
  '# Multi-window burn-rate alerts (one per declared window), forecast alerts and the',
  '# error-budget recording rules. Names/labels follow Observogram\'s compiler; the library',
  '# header (vendor/observogram/lib/burn-rules.mjs) lists the five PromQL deviations (bad/expected',
  '# ratios, short-window floor, sustained-burn forecasts, lab for:, capped horizon + severity).',
  '# Regenerate: npm run burn-rules',
  '',
];
writeFileSync(resolve(root, OUT), toYaml(r.groups, header));
console.log(`${OUT}: ${r.recording.length} recording rules, ${r.burnCount} burn-rate alerts, ${r.forecasts.length} forecast alerts`);
